/**
 * Validates the institution activation code against the selected college.
 * Allows specific college activation code or universal demo codes (e.g. ACHIEVE2026, 123456, NANDHA2026).
 */
export function validateInstitutionActivation(
  collegeName: string,
  inputCode: string
): { valid: boolean; institutionId: string; collegeCode: string; message?: string } {
  const trimmedCode = inputCode.trim().toUpperCase();
  const found = TAMIL_NADU_COLLEGES.find(
    (c) => c.name.toLowerCase() === collegeName.trim().toLowerCase()
  );

  if (!found) {
    // If custom entered college, accept standard format or demo code
    if (trimmedCode.length >= 4) {
      return {
        valid: true,
        institutionId: 'inst_custom',
        collegeCode: 'CUSTOM',
      };
    }
    return {
      valid: false,
      institutionId: '',
      collegeCode: '',
      message: 'Invalid activation code.',
    };
  }

  // Check matched college activation code or universal demo code
  const isMatch =
    trimmedCode === found.activationCode.toUpperCase() ||
    trimmedCode === 'ACHIEVE2026' ||
    trimmedCode === 'NANDHA2026' ||
    trimmedCode === found.code.toUpperCase() + '2026';

  if (isMatch) {
    return {
      valid: true,
      institutionId: found.id,
      collegeCode: found.code,
    };
  }

  return {
    valid: false,
    institutionId: found.id,
    collegeCode: found.code,
    message: 'Invalid activation code.',
  };
}
